import chalk from "chalk";
import { task, types } from "hardhat/config";
import type { HardhatRuntimeEnvironment, TaskArguments } from "hardhat/types";
import { Contract, Wallet } from "ethers";
import { HardhatEthersSigner } from "@nomicfoundation/hardhat-ethers/signers";

import { resolveTaskManager } from "../utils/addressBook";
import { execTransactionThroughSafe, writeSafeBatch } from "../utils/safe";
import { confirm } from "../utils/confirm";
import { implementationOf, runsCurrentBuild, waitForNonce } from "../utils/upgrade";
import { validateUpgrade } from "./storageLayout";

const REGISTRY_SOURCE = "contracts/ACPShareRegistry.sol";
const REGISTRY_NAME = "ACPShareRegistry";

/**
 * Whether the proxy runs a pointer-based implementation, told by `share(acp, metadata)` in its
 * function dispatcher (`PUSH4 <selector>`); the first version has only `share(acp)`.
 */
async function runsPointerImplementation(ethers: any, proxy: string, Factory: any): Promise<boolean> {
  const selector: string = Factory.interface.getFunction("share").selector;
  const code: string = await ethers.provider.getCode(await implementationOf(ethers, proxy));
  return code.toLowerCase().includes("63" + selector.slice(2).toLowerCase());
}

/**
 * Who sends the upgrade: the signer, which must hold UPGRADER_ROLE, or with `viaSafe` the Safe at
 * SAFE_ADMIN_ADDRESS, which must hold it (the post-handover flow). Null for the signer.
 */
async function resolveSender(ethers: any, registry: any, signer: any, viaSafe: boolean): Promise<string | null> {
  const upgraderRole = await registry.UPGRADER_ROLE();
  if (!viaSafe) {
    if (!(await registry.hasRole(upgraderRole, signer.address))) {
      throw new Error(
        `Refusing to upgrade ACPShareRegistry: the signer ${signer.address} lacks UPGRADER_ROLE. ` +
          `After the handover use task:upgradeShareRegistryAsSafe.`,
      );
    }
    return null;
  }
  const rawSafe = process.env.SAFE_ADMIN_ADDRESS?.trim();
  if (!rawSafe) {
    throw new Error("SAFE_ADMIN_ADDRESS must be set");
  }
  const safe = ethers.getAddress(rawSafe);
  if (!(await registry.hasRole(upgraderRole, safe))) {
    throw new Error(
      `Refusing to upgrade ACPShareRegistry: ${safe} does not hold UPGRADER_ROLE. ` +
        `Was the handover step of the deployment run?`,
    );
  }
  return safe;
}

/**
 * Sends `upgradeToAndCall(impl, 0x)`: as the signer (with `nonce`), through the Safe with SAFE_OWNER_KEY, or as
 * a Transaction Builder batch to import in the Safe app. True when it was sent from here.
 */
async function sendUpgrade(
  hre: HardhatRuntimeEnvironment,
  signer: any,
  safe: string | null,
  proxy: string,
  data: string,
  nonce: number,
  out?: string,
): Promise<boolean> {
  const { ethers } = hre;
  if (safe === null) {
    await (await signer.sendTransaction({ to: proxy, data, nonce })).wait();
    console.log(chalk.green("Upgraded ACPShareRegistry"));
    return true;
  }

  const ownerKey = process.env.SAFE_OWNER_KEY?.trim();
  if (ownerKey) {
    const ownerSigner = new Wallet(ownerKey, ethers.provider);
    // An EOA final admin (testnets) sends directly: SAFE_OWNER_KEY is then its own key.
    if (ownerSigner.address.toLowerCase() === safe.toLowerCase()) {
      await (await ownerSigner.sendTransaction({ to: proxy, data })).wait();
    } else {
      await execTransactionThroughSafe(hre, safe, ownerSigner, proxy, data);
    }
    console.log(chalk.green(`Upgraded ACPShareRegistry as ${safe}`));
    return true;
  }

  const path = writeSafeBatch(hre, {
    safeAddress: safe,
    slug: "upgrade-share-registry",
    name: "CoFHE - upgrade ACPShareRegistry",
    description: `Upgrade the ACPShareRegistry proxy ${proxy} in place. Generated by task:upgradeShareRegistryAsSafe.`,
    transactions: [{ to: proxy, data }],
    outPath: out,
  });
  console.log(chalk.bold.blue("\nSAFE_OWNER_KEY not set - wrote a Safe Transaction Builder batch:"));
  console.log(`  ${path}`);
  console.log(chalk.dim("Import it under Apps -> Transaction Builder in the Safe app, review, sign, execute."));
  console.log(`  to: ${proxy}\n  data: ${data}`);
  console.log(chalk.yellow("Re-run this task after execution to verify - an upgraded proxy is reported as done."));
  return false;
}

/**
 * Upgrades the ACL's ACPShareRegistry in place to this build, from the first version or from an
 * earlier pointer-based one. The signer deploys the implementation; the upgrade itself is sent by
 * the signer, or with `viaSafe` by the Safe at SAFE_ADMIN_ADDRESS. A proxy already on this build is
 * left alone, so a re-run after a Safe batch executes verifies it.
 */
async function upgradeShareRegistry(
  hre: HardhatRuntimeEnvironment,
  taskArguments: TaskArguments,
  viaSafe: boolean,
) {
  const { ethers, upgrades } = hre;
  const signer: HardhatEthersSigner =
    taskArguments.key === ""
      ? (await ethers.getSigners())[2]
      : (new Wallet(taskArguments.key).connect(ethers.provider) as unknown as HardhatEthersSigner);
  console.log(chalk.green("Network:", hre.network.name, "signer:", signer.address));

  const taskManagerAddress = await resolveTaskManager(hre);
  const taskManager: any = await ethers.getContractAt("TaskManager", taskManagerAddress);
  const acl: any = await ethers.getContractAt("ACL", await taskManager.acl());
  const proxy: string = await acl.shareRegistry();
  if (proxy === ethers.ZeroAddress) {
    throw new Error(`ACL ${await acl.getAddress()} serves no share registry (shareRegistry() is zero).`);
  }
  const oldImplementation = await implementationOf(ethers, proxy);
  console.log(chalk.green("TaskManager:", taskManagerAddress));
  console.log(chalk.green("ACPShareRegistry proxy:", proxy));
  console.log(chalk.green("Current implementation:", oldImplementation));

  const Factory = await ethers.getContractFactory(REGISTRY_NAME);
  if (await runsCurrentBuild(hre, proxy, REGISTRY_SOURCE, REGISTRY_NAME)) {
    console.log(chalk.green("The proxy already runs this ACPShareRegistry build. Nothing to do."));
    return;
  }

  if (await runsPointerImplementation(ethers, proxy, Factory)) {
    await validateUpgrade(hre, REGISTRY_NAME, Factory);
  } else {
    // The snapshot holds the pointer-based layout, so the first version is checked against its own source.
    await upgrades.forceImport(proxy, await ethers.getContractFactory("ACPShareRegistryV1"), { kind: "uups" });
    await upgrades.validateUpgrade(proxy, Factory, { kind: "uups" });
    console.log(chalk.green("✅ Storage layout is compatible with the first version"));
  }
  if (taskArguments.onlyvalidate) return;

  const registry = Factory.attach(proxy) as Contract;
  const safe = await resolveSender(ethers, registry, signer, viaSafe);
  const question =
    `Upgrade ACPShareRegistry ${proxy} on ${hre.network.name}` +
    `${safe === null ? ` as ${signer.address}` : ` through Safe ${safe}`}?`;
  if (!(await confirm(question, taskArguments.yes))) {
    console.log(chalk.yellow("Aborted - nothing was deployed or sent."));
    return;
  }
  const implementation = await Factory.connect(signer).deploy();
  await implementation.waitForDeployment();
  const newImplementation = await implementation.getAddress();
  console.log(chalk.green("New implementation:", newImplementation));
  const deployNonce = implementation.deploymentTransaction()!.nonce;
  await waitForNonce(ethers, signer.address, deployNonce);

  // From the first version, its shares are abandoned, not migrated: they stay in its storage, unread.
  const data = Factory.interface.encodeFunctionData("upgradeToAndCall", [newImplementation, "0x"]);
  if (await sendUpgrade(hre, signer, safe, proxy, data, deployNonce + 1, taskArguments.out)) {
    const now = await implementationOf(ethers, proxy);
    console.log(chalk.green("Implementation now:", now));
    if (now === oldImplementation) console.log(chalk.red("WARNING: Implementation address did not change!"));
  }
}

task("task:upgradeShareRegistry", "Upgrade the ACL's ACPShareRegistry in place to this build")
  .addParam("key", "Signer key holding UPGRADER_ROLE (default: the third configured account)", "")
  .addParam("onlyvalidate", "Only validate the storage layout", false, types.boolean)
  .addFlag("yes", "Skip the confirmation prompt")
  .setAction(async function (taskArguments: TaskArguments, hre) {
    await upgradeShareRegistry(hre, taskArguments, false);
  });

task("task:upgradeShareRegistryAsSafe", "Upgrade the ACL's ACPShareRegistry in place through the Safe")
  .addParam("key", "Any funded key, deploys the implementation (default: the third configured account)", "")
  .addParam("onlyvalidate", "Only validate the storage layout", false, types.boolean)
  .addOptionalParam("out", "Path for the Safe batch file, when one is written")
  .addFlag("yes", "Skip the confirmation prompt")
  .setAction(async function (taskArguments: TaskArguments, hre) {
    await upgradeShareRegistry(hre, taskArguments, true);
  });
