import { config as dotenvConfig } from "dotenv";
import { resolve } from "path";
import { task } from "hardhat/config";
import chalk from "chalk";
import { HardhatRuntimeEnvironment, TaskArguments } from "hardhat/types";

import { execTransactionThroughSafe, writeSafeBatch } from "../utils/safe";
import { resolveDefaultAdminAuthority, resolveRolesByName } from "../utils/roles";
import { resolveTaskManager } from "../utils/addressBook";

const dotenvConfigPath: string = process.env.DOTENV_CONFIG_PATH || "../.env";
dotenvConfig({ path: resolve(__dirname, dotenvConfigPath) });

/**
 * Grants one of the TaskManager's `*_ROLE`s to an account.
 *
 * Every role is administered by DEFAULT_ADMIN_ROLE, so the grant is sent by whoever holds it: the
 * signer before the handover, the Safe at SAFE_ADMIN_ADDRESS afterwards - through it with
 * SAFE_OWNER_KEY (an EOA final admin sends directly), otherwise as one Transaction Builder batch.
 * An account that already holds the role is left alone, so a re-run after the batch executes
 * verifies it. DEFAULT_ADMIN_ROLE itself is refused: it moves via the two-step transfer.
 * With `viaSafe` the signer is never used: the grant always goes through the Safe.
 */
async function grantRole(hre: HardhatRuntimeEnvironment, taskArguments: TaskArguments, viaSafe: boolean) {
  const { ethers } = hre;
  const roleName = String(taskArguments.role).trim();
  if (!/^[A-Z0-9_]+_ROLE$/.test(roleName)) {
    throw new Error(`${roleName} is not a role name - pass the constant, e.g. ACCESS_LIST_MANAGER_ROLE.`);
  }
  if (roleName === "DEFAULT_ADMIN_ROLE") {
    throw new Error(
      "DEFAULT_ADMIN_ROLE cannot be granted - it moves via the two-step transfer " +
        "(beginDefaultAdminTransfer, then task:acceptAdminAsSafe).",
    );
  }
  const account = ethers.getAddress(String(taskArguments.account).trim());
  if (account === ethers.ZeroAddress) {
    throw new Error("refusing to grant a role to address(0).");
  }

  const tmAddress = await resolveTaskManager(hre);
  const taskManager: any = await ethers.getContractAt("TaskManager", tmAddress);
  console.log(chalk.dim(`TaskManager: ${tmAddress} on ${hre.network.name}`));
  const [{ role }] = await resolveRolesByName(taskManager, [roleName]);

  if (await taskManager.hasRole(role, account)) {
    console.log(chalk.green(`${account} already holds ${roleName} - nothing to do`));
    return;
  }

  const call = `grantRole(${roleName}, ${account})`;
  const data = taskManager.interface.encodeFunctionData("grantRole", [role, account]);
  const authority = await resolveDefaultAdminAuthority(hre, taskManager, viaSafe);

  if (authority.kind === "signer") {
    await (await taskManager.connect(authority.signer).grantRole(role, account)).wait();
  } else if (authority.ownerSigner) {
    console.log(
      chalk.green(`Granting as Safe ${authority.safeAddress}, sending as owner ${authority.ownerSigner.address}`),
    );
    if (authority.ownerSigner.address.toLowerCase() === authority.safeAddress.toLowerCase()) {
      await (await authority.ownerSigner.sendTransaction({ to: tmAddress, data })).wait();
    } else {
      await execTransactionThroughSafe(hre, authority.safeAddress, authority.ownerSigner, tmAddress, data);
    }
  } else {
    const path = writeSafeBatch(hre, {
      safeAddress: authority.safeAddress,
      slug: `grant-${roleName.toLowerCase().replace(/_/g, "-")}`,
      name: `CoFHE - grant ${roleName}`,
      description: `${call} on TaskManager ${tmAddress}. Generated by task:grantRole${viaSafe ? "AsSafe" : ""}.`,
      transactions: [{ to: tmAddress, data }],
      outPath: taskArguments.out,
    });
    console.log(chalk.bold.blue("\nSAFE_OWNER_KEY not set - wrote a Safe Transaction Builder batch:"));
    console.log(`  ${path}`);
    console.log(`  ${call}`);
    console.log(`    to:    ${tmAddress}`);
    console.log(`    value: 0`);
    console.log(`    data:  ${data}`);
    console.log(
      chalk.yellow(
        "Import it in the Safe app under Apps -> Transaction Builder, review, sign and execute. " +
          "Re-run this task afterwards to verify.",
      ),
    );
    return;
  }

  if (!(await taskManager.hasRole(role, account))) {
    throw new Error(`${account}: the transaction executed but hasRole(${roleName}) is still false.`);
  }
  console.log(chalk.green(`${account} now holds ${roleName}`));
}

task("task:grantRole", "Grant one of the TaskManager's roles to an account")
  .addParam("role", "The role's constant name, e.g. ACCESS_LIST_MANAGER_ROLE")
  .addParam("account", "The address receiving the role")
  .addOptionalParam("out", "Path for the Safe batch file, when one is written")
  .setAction(async function (taskArguments, hre) {
    await grantRole(hre, taskArguments, false);
  });

task("task:grantRoleAsSafe", "Grant one of the TaskManager's roles to an account through the Safe")
  .addParam("role", "The role's constant name, e.g. ACCESS_LIST_MANAGER_ROLE")
  .addParam("account", "The address receiving the role")
  .addOptionalParam("out", "Path for the Safe batch file, when one is written")
  .setAction(async function (taskArguments, hre) {
    await grantRole(hre, taskArguments, true);
  });
